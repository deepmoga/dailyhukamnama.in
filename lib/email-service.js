import nodemailer from 'nodemailer';
import { getAllSettings } from './settings-service.js';

/**
 * Build nodemailer transport from database settings
 */
async function getTransporter() {
  const settings = await getAllSettings();

  const host = settings.smtp_host || 'smtp.gmail.com';
  const port = parseInt(settings.smtp_port, 10) || 465;
  const isSecure = settings.smtp_secure === '1' || port === 465;
  const user = (settings.smtp_user || '').trim();
  // Strip spaces from Google App Passwords (e.g. "rdfv ukzs nbdo mvir" -> "rdfvukzsnbdomvir")
  const pass = (settings.smtp_pass || '').replace(/\s+/g, '').trim();

  const transporter = nodemailer.createTransport({
    host,
    port,
    secure: isSecure,
    auth: {
      user,
      pass,
    },
    // Useful for Gmail
    tls: {
      rejectUnauthorized: false,
    },
  });

  return { transporter, settings };
}

